// 占位图 emoji：食材 / 菜谱没有真实图片时，按名称与类别给出贴切图标
// 规则数组顺序即优先级。菜名判断要点：
//   - 意面最优先（番茄肉酱意面 / 黑椒牛肉意面 等统一显示面条）
//   - 鱼香是味型不是鱼（鱼香肉丝 → 肉）
//   - 蛋在肉类之前（鸡蛋 / 蒸蛋 不判成鸡）
//   - 蔬菜在主食与调味之前（蒜蓉粉丝蒸娃娃菜 的「菜」压过「粉丝」，蚝油生菜 的「菜」压过「蚝油」）
//   - 汤类兜底放最后（莲藕排骨汤 已按 排骨→肉 显示，番茄鱼片汤 已按 鱼 显示）

const NAME_RULES = [
  // 菜名特判：意面 / 鱼香味型
  [/意面/, '🍜'],
  [/鱼香/, '🥩'],
  // 蛋（先于肉类）
  [/蛋/, '🥚'],
  // 水产
  [/虾/, '🦐'],
  [/鱼|蟹|贝|蛤|鱿|蛏|海参/, '🐟'],
  // 肉类（含排骨：莲藕排骨汤等汤菜按肉显示）
  [/猪|牛|羊|鸡|鸭|鹅|培根|火腿|午餐肉|里脊|腊|肉|排骨/, '🥩'],
  // 菌菇
  [/菇|蘑|木耳|菌/, '🍄'],
  // 乳制品 / 饮品
  [/奶酪|芝士/, '🧀'],
  [/黄油/, '🧈'],
  [/牛奶|酸奶|豆浆|奶/, '🥛'],
  // 豆制品（豆腐按豆制品显示）
  [/豆腐|豆干|腐竹|豆皮/, '🫘'],
  // 蔬菜：具体果蔬给专属图标，其余统一 🥬
  // 注意：番茄 含「茄」须在蔬菜兜底之前；不含 葱/蒜/姜（调味料交给 isVegetable 兜底，避免葱油拌面被误判成菜）
  [/面粉|淀粉/, '🌾'],
  [/番茄|圣女果/, '🍅'],
  [/柠檬/, '🍋'],
  [/土豆/, '🥔'],
  [/胡萝卜|萝卜/, '🥕'],
  [/玉米/, '🌽'],
  [/南瓜/, '🎃'],
  [/辣椒/, '🌶'],
  [/菜|茄|瓜|藕|笋|青椒|彩椒|芹|豆芽|山药|洋葱|甘蓝/, '🥬'],
  // 主食
  [/面包|吐司/, '🍞'],
  [/三明治/, '🥪'],
  [/饺子|馒头|包子|饼|馄饨/, '🥟'],
  [/面条|拌面|炒面|焖面|凉面|汤面|米线|米粉|粉丝|粉条|面/, '🍜'],
  [/米饭|炒饭|盖饭|大米|糯米|黑米|糙米|小米/, '🍚'],
  // 调味（干辣椒/胡椒/花椒等在蔬菜兜底未命中时走这里）
  [/生抽|老抽|酱油|蚝油|醋|料酒|咖喱|盐|糖|胡椒|花椒|食用油|油/, '🧂'],
  // 汤羹兜底
  [/汤|羹|粥/, '🍲']
]

/**
 * 根据名称与类别返回占位 emoji
 * @param {string} name 食材 / 菜谱 / 运动名称
 * @param {{ isVegetable?: boolean, isStaple?: boolean }} options 分类标记
 */
export function foodEmoji(name, options = {}) {
  const n = (name || '').trim()
  for (const [re, emoji] of NAME_RULES) {
    if (re.test(n)) return emoji
  }
  // 蔬菜类：统一使用青菜占位图
  if (options.isVegetable) return '🥬'
  if (options.isStaple) return '🍚'
  return '🍽️'
}

export default foodEmoji
